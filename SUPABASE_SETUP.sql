grant insert, select, update on public.zenvix_orders to authenticated;
grant usage, select on sequence public.zenvix_orders_id_seq to authenticated;
grant select on public.zenvix_admin_users to authenticated;
grant insert, update on public.zenvix_delivery_settings to authenticated;
drop policy if exists "Anyone can read storefront settings" on public.zenvix_store_settings;
create policy "Anyone can read storefront settings" on public.zenvix_store_settings for select to anon,authenticated using(true);
drop policy if exists "Admins can insert storefront settings" on public.zenvix_store_settings;
create policy "Admins can insert storefront settings" on public.zenvix_store_settings for insert to authenticated with check(public.is_zenvix_admin());
drop policy if exists "Admins can update storefront settings" on public.zenvix_store_settings;
