-- ZENVIX shared orders, delivery settings, and admin access.
-- Run this in Supabase Dashboard -> SQL Editor.

create table if not exists public.zenvix_admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.zenvix_orders (
  id bigint generated by default as identity primary key,
  order_number text not null unique,
  order_data jsonb not null,
  user_id uuid references auth.users(id) on delete set null,
  status text not null default 'Pending' check (status in ('Pending','Confirmed','Shipped','Delivered','Cancelled')),
  created_at timestamptz not null default now()
);

-- Upgrade existing guest-order installations. Older orders remain admin-only because user_id is NULL.
alter table public.zenvix_orders add column if not exists user_id uuid references auth.users(id) on delete set null;

