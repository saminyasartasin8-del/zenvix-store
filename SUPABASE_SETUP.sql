grant select on public.zenvix_store_settings to anon,authenticated;
grant insert,update on public.zenvix_store_settings to authenticated;

-- Product data is public to read, while product changes are admin-only.
do $$
declare p record;
begin
  for p in select policyname, tablename from pg_policies
    where schemaname='public' and tablename in ('products','product_images')
  loop
    execute format('drop policy %I on public.%I', p.policyname, p.tablename);
  end loop;
end $$;

create policy "Anyone can read active products" on public.products
for select to anon, authenticated using (active = true);
create policy "Admins can manage products" on public.products
for all to authenticated using (public.is_zenvix_admin()) with check (public.is_zenvix_admin());
create policy "Anyone can read product images" on public.product_images
for select to anon, authenticated using (true);
create policy "Admins can manage product images" on public.product_images
for all to authenticated using (public.is_zenvix_admin()) with check (public.is_zenvix_admin());

grant select on public.products, public.product_images to anon, authenticated;
grant insert, update, delete on public.products, public.product_images to authenticated;

-- Reuse the existing public bucket if present; do not alter its size settings.
insert into storage.buckets (id, name, public)
values ('product-images', 'product-images', true)
on conflict (id) do update set public = true;

-- Remove bucket-specific permissive policies before installing admin-only writes.
do $$
declare p record;
begin
  for p in select policyname from pg_policies
    where schemaname='storage' and tablename='objects'
      and (coalesce(qual,'') like '%product-images%' or coalesce(with_check,'') like '%product-images%')
  loop
    execute format('drop policy %I on storage.objects', p.policyname);
  end loop;
end $$;

create policy "Zenvix product images public read" on storage.objects
for select to anon, authenticated using (bucket_id = 'product-images');
create policy "Zenvix admins upload product images" on storage.objects
for insert to authenticated with check (bucket_id = 'product-images' and public.is_zenvix_admin());
create policy "Zenvix admins update product images" on storage.objects
for update to authenticated using (bucket_id = 'product-images' and public.is_zenvix_admin())
with check (bucket_id = 'product-images' and public.is_zenvix_admin());
create policy "Zenvix admins remove product images" on storage.objects
for delete to authenticated using (bucket_id = 'product-images' and public.is_zenvix_admin());

