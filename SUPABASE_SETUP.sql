-- Replace every existing order policy so guest inserts cannot bypass ownership checks.
do $$
declare p record;
begin
  for p in select policyname from pg_policies where schemaname='public' and tablename='zenvix_orders' loop
    execute format('drop policy %I on public.zenvix_orders', p.policyname);
  end loop;
end $$;

-- Remove/recreate the remaining policies safely when this script is rerun.
drop policy if exists "Admins can read their own admin grant" on public.zenvix_admin_users;
create policy "Admins can read their own admin grant"
on public.zenvix_admin_users for select to authenticated
using (user_id = auth.uid());

create policy "Customers can submit their own orders"
on public.zenvix_orders for insert to authenticated
with check (
  order_number is not null and length(order_number) between 3 and 40
  and jsonb_typeof(order_data) = 'object'
  and user_id = auth.uid()
  and order_data->>'user_id' = auth.uid()::text
  and lower(order_data->>'email') = lower(auth.jwt()->>'email')
  and status = 'Pending'
);

create policy "Customers can view their own orders"
on public.zenvix_orders for select to authenticated
using (user_id = auth.uid());

create policy "Admins can view orders"
on public.zenvix_orders for select to authenticated
using (public.is_zenvix_admin());

create policy "Admins can update order status"
on public.zenvix_orders for update to authenticated
using (public.is_zenvix_admin())
with check (public.is_zenvix_admin());

drop policy if exists "Anyone can read delivery settings" on public.zenvix_delivery_settings;
create policy "Anyone can read delivery settings"
on public.zenvix_delivery_settings for select to anon, authenticated
using (true);

drop policy if exists "Admins can insert delivery settings" on public.zenvix_delivery_settings;
create policy "Admins can insert delivery settings"
on public.zenvix_delivery_settings for insert to authenticated
with check (public.is_zenvix_admin());

drop policy if exists "Admins can update delivery settings" on public.zenvix_delivery_settings;
create policy "Admins can update delivery settings"
on public.zenvix_delivery_settings for update to authenticated
using (public.is_zenvix_admin())
with check (public.is_zenvix_admin());

grant select on public.zenvix_delivery_settings to anon, authenticated;
