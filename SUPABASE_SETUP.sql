-- Match product_images.product_id to the existing products.id type.
do $$
declare product_id_type text;
begin
  select format_type(a.atttypid, a.atttypmod) into product_id_type
  from pg_attribute a
  where a.attrelid = 'public.products'::regclass and a.attname = 'id' and not a.attisdropped;
  if product_id_type is null then raise exception 'public.products must have an id column'; end if;
  execute format('create table if not exists public.product_images (
    id bigint generated by default as identity primary key,
    product_id %s not null references public.products(id) on delete cascade,
    url text not null,
    sort_order integer not null default 0,
    created_at timestamptz not null default now()
  )', product_id_type);
end $$;

alter table public.product_images add column if not exists url text;
alter table public.product_images add column if not exists sort_order integer not null default 0;
alter table public.product_images add column if not exists media_type text not null default 'image';
alter table public.product_images add column if not exists created_at timestamptz not null default now();

create or replace function public.is_zenvix_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.zenvix_admin_users where user_id = auth.uid());
$$;

